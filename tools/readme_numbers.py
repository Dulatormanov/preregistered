"""make readme: the numbers on the README's first screen, generated, never typed (Build day 8).

  OBSERVER_DB_URL=... python tools/readme_numbers.py   rewrites the block between the README's numbers markers
Counts from the ledger (as observer), the noise floor and the sealed result if it exists. Nothing about a person.
"""
import json
import os
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

import psycopg

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tools.tables import window_so_far  # noqa: E402

START, END = "<!-- numbers: generated by make readme, do not edit -->", "<!-- /numbers -->"


def block(db):
    seen, champion, baseline, anchors, spend, ticks, scheduled = db.execute("""select
        (select count(*) from prereg.issues_seen),
        (select count(*) from prereg.predictions where champion_id <> 'rules_v0'),
        (select count(*) from prereg.predictions where champion_id = 'rules_v0'),
        (select count(*) from prereg.anchors),
        (select coalesce(sum(cost_usd), 0) from prereg.steps where job = 'tick'),
        (select count(*) from prereg.run_events where kind = 'polled'),
        (select count(*) from prereg.run_events where kind = 'polled' and data->>'trigger' = 'schedule')""").fetchone()
    live = window_so_far(db)
    floor = json.loads((ROOT / "gate/noise_floor.json").read_text())
    sealed = ROOT / "results/sealed.json"
    lines = [f"Numbers as of {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC, from the ledger:",
             f"- {seen} issues seen; {champion} champion guesses and {baseline} baseline guesses, under {anchors} anchors"
             f" on the Notary log;",
             f"- {ticks} ticks, {scheduled} of them started by GitHub's schedule; their model calls cost ${float(spend):.4f};",
             f"- the dev set (186 issues, the 5 A/A runs at commit {floor['commit'][:7]}): agreement"
             f" {min(floor['agreement']):.1%} to {max(floor['agreement']):.1%};",
             "- the live window (issues created from 2026-11-07 to 2026-11-13): " + ("; ".join(
                 f"{series} {matched} of {counting} counting guesses right ({scorable} scorable)"
                 for series, counting, matched, scorable in live) or "no scorable issue yet") + ";",
             "- the sealed set: " + (f"agreement {json.loads(sealed.read_text())['agreement']:.1%}, promoted: "
                                     f"{', '.join(json.loads(sealed.read_text())['promoted']) or 'none'}"
                                     if sealed.exists() else "scored once, on or after 2026-11-08") + "."]
    return "\n".join(lines)


def main():
    readme = ROOT / "README.md"
    with psycopg.connect(os.environ["OBSERVER_DB_URL"], autocommit=True) as db:
        numbers = block(db)
    text = readme.read_text()
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), f"{START}\n{numbers}\n{END}", text, flags=re.S)
    readme.write_text(new)
    print(numbers)


if __name__ == "__main__":
    main()
